export const ICON_RE = /^(lucide:[a-z0-9-]{1,40}|emoji:\S{1,16})$/u;
export const COLOR_RE = /^#[0-9a-f]{6}$/i;

export function searchIcons(q: string): IconDef[] {
  const s = q.trim().toLowerCase();
  if (!s) return ICONS;
  return ICONS.filter((i) => i.id.includes(s) || i.tags.split(" ").some((t) => t.startsWith(s)));
}

export function searchEmojis(q: string): [string, string][] {
  const s = q.trim().toLowerCase();
  if (!s) return EMOJIS;
  return EMOJIS.filter(([, name]) => name.split(" ").some((t) => t.startsWith(s)));
}
